def audio():
    SR=16000
    tracks={
        'morning-sorting':(8.0,[261.63,329.63,392.0,523.25],.14,.7),
        'hanging-gardens':(8.0,[293.66,369.99,440.0,587.33],.11,.6),
        'cloud-waltz':(8.0,[220.0,293.66,349.23,440.0],.13,.55),
        'first-light':(8.0,[261.63,392.0,523.25,659.25],.15,.8),
        'brass-bell':(1.4,[392.0,784.0,1176.0],.27,1.4),
        'teacup':(.7,[659.25,988.9,1318.5],.15,2.0),
        'wing-flutter':(.65,[300.0,380.0,475.0],.09,3.0),
    }
    for name,(duration,notes,gain,decay) in tracks.items():
        n=int(SR*duration); data=bytearray()
        for i in range(n):
            t=i/SR
            # A composed four-beat ascending/descending original arpeggio.
            idx=(int(t*2.2) if duration>3 else 0)%len(notes)
            hz=notes[idx]
            p=t*2*math.pi
            if name=='wing-flutter':waveform=math.sin(p*(hz+53*math.sin(2*math.pi*17*t)))*math.sin(p*18)
            else:
                waveform=.62*math.sin(p*hz)+.25*math.sin(p*hz*2.01)+.13*math.sin(p*hz*.5)
            fade_in=min(1.0,t/.045)
            fade_out=min(1.0,(duration-t)/(.7 if duration>3 else .22))
            envelope=fade_in*max(0,fade_out)*(math.exp(-t/decay) if duration<3 else .6+.4*math.sin(math.pi*t/duration)**2)
            amplitude=int(max(-32767,min(32767,waveform*gain*envelope*32767)))
            data.extend(struct.pack('<h',amplitude))
        with wave.open(str(AUD/(name+'.wav')),'wb') as wav:
            wav.setnchannels(1); wav.setsampwidth(2); wav.setframerate(SR);wav.writeframes(data)

